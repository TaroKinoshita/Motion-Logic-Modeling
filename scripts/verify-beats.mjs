import path from 'node:path';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const root = path.resolve(import.meta.dirname, '..');
process.env.MLM_DATA_DIR = path.join(root, 'data/v2-validation');
const { detectBeats } = await import('../apps/server/src/beats.ts');
const { getProject } = await import('../apps/server/src/store.ts');
const report = JSON.parse(fs.readFileSync(path.join(process.env.MLM_DATA_DIR, 'report.json')));
const id = report.projects[1];
const before = getProject(id);
const manual = before.scene.markers.filter(m => m.origin === 'manual');
const first = await detectBeats(id, before.project.revision, 'test');
const second = await detectBeats(id, first.project.revision, 'test');
const after = getProject(id);
assert.deepEqual(after.scene.markers.filter(m => m.origin === 'manual'), manual);
assert.deepEqual(after.scene.tempo, before.scene.tempo);
assert.equal(after.scene.markers.filter(m => m.kind === 'beat' && m.origin === 'estimated').length, second.beats.length);
const errors = second.beats.map(t => Math.abs(t - Math.round(t * 2) / 2));
const result = { bpm: second.bpm, beats: second.beats, maxNearestGridErrorSeconds: Math.max(...errors), withinOneFrame: errors.filter(e => e <= 1/30).length, count: errors.length, manualPreserved: true, tempoUnchanged: true, rerunReplacesEstimated: true };
fs.writeFileSync(path.join(process.env.MLM_DATA_DIR, 'beats-verification.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
