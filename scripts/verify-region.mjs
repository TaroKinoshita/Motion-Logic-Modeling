import assert from 'node:assert/strict';
import { createCanvas, loadImage } from '@napi-rs/canvas';
import { emptyScene } from '../packages/core/src/index.ts';
import { renderSheet } from '../apps/server/src/render.ts';
const scene = emptyScene(); scene.width = 400; scene.height = 300; scene.background = '#000000';
scene.elements = [{ id: 'target', type: 'rect', width: 40, height: 40, fill: '#ff0000', transform: { x: 100, y: 100 } }];
const project = { id: 'region-test', name: 'test', schemaVersion: 2, revision: 1, createdAt: '', updatedAt: '' };
const options = { kind: 'render', times: [0], cellWidth: 200, region: { x: 50, y: 50, w: 100, h: 100 } };
const img = await loadImage(await renderSheet(project, scene, options));
assert.equal(img.width, 208); assert.equal(img.height, 208);
const ctx = createCanvas(208, 208).getContext('2d'); ctx.drawImage(img, 0, 0);
const center = ctx.getImageData(104, 104, 1, 1).data;
assert.ok(center[0] > 240 && center[1] < 15 && center[2] < 15);
assert.ok(ctx.getImageData(20, 104, 1, 1).data[0] < 15);
await assert.rejects(renderSheet(project, scene, { ...options, region: { x: 399, y: 0, w: 2, h: 2 } }), /region/);
await assert.rejects(renderSheet(project, scene, { ...options, gridStep: 0 }), /gridStep/);
const grid = await renderSheet(project, scene, { ...options, gridStep: 25 });
assert.notDeepEqual(grid, await renderSheet(project, scene, options));
console.log('PASS: crop geometry, dimensions, pixel location, bounds, grid overlay');
